"""Generates src/Colony.Core/Numerics/FixedTables.cs and prints golden values for the fixed-point trig tests.

Usage (from the repo root): python -I tools/scripts/gen_fixed_tables.py src/Colony.Core/Numerics/FixedTables.cs

Quarter-wave sine table: 1025 entries covering [0, pi/2] in Q32 (value * 2^32), as longs.
Arctangent table: 1025 entries covering atan(t) for t in [0, 1] in Q32 radians.
Both are rounded to nearest from double precision (accurate to ~1e-16, far below the Q32
half-ulp of 1.2e-10 except for astronomically rare ties). The tables are committed so that
no platform math runs at startup (spec section 6); regenerate only if the step count changes.
"""
import math, sys

N = 1024
SCALE = 1 << 32

def q32(x):
    return int(math.floor(x * SCALE + 0.5))

sin_table = [q32(math.sin((math.pi / 2) * i / N)) for i in range(N + 1)]
atan_table = [q32(math.atan(i / N)) for i in range(N + 1)]
assert sin_table[-1] == SCALE
assert atan_table[-1] == q32(math.pi / 4)

def emit(name, table, out):
    # A static readonly array, not a `ReadOnlySpan<long> => [...]` RVA property: under the tier-0 JIT
    # RuntimeHelpers.CreateSpan is not an intrinsic and allocates ~72 bytes per access, which the
    # allocation harness would flag. The array is initialised once at type load.
    out.write(f"    internal static ReadOnlySpan<long> {name} => {name}Data;\n\n")
    out.write(f"    private static readonly long[] {name}Data =\n    [\n")
    for i in range(0, len(table), 8):
        out.write("        " + ", ".join(f"0x{v:X}L" for v in table[i:i+8]) + ",\n")
    out.write("    ];\n")

with open(sys.argv[1], "w", newline="\n") as out:
    out.write("// <auto-generated>\n")
    out.write("// Generated by tools/scripts/gen_fixed_tables.py (quarter-wave sine and arctangent, Q32, 1024 steps).\n")
    out.write("// Committed as literals so no platform math runs at startup (spec section 6).\n")
    out.write("// </auto-generated>\n\n")
    out.write("namespace Colony.Numerics;\n\n")
    out.write("internal static class FixedTables\n{\n")
    out.write(f"    internal const int Steps = {N};\n\n")
    emit("SinQuarterQ32", sin_table, out)
    out.write("\n")
    emit("AtanUnitQ32", atan_table, out)
    out.write("}\n")

# Golden values for tests (Q16.16 raw ints and Q32.32 raw longs)
def q16(x):
    return int(math.floor(x * 65536 + 0.5)) if x >= 0 else -int(math.floor(-x * 65536 + 0.5))
for a in [0.0, 0.5, 1.0, 1.5707963267948966, 2.0, 3.0, 3.141592653589793, -1.0, 10.0, 100.0]:
    print(f"x={a}: raw16={q16(a)} sin16={q16(math.sin(a))} cos16={q16(math.cos(a))} sin32={q32(math.sin(a)) if math.sin(a)>=0 else -q32(-math.sin(a))}")
for y, x in [(1,1),(1,0),(0,1),(-1,-1),(0,-1),(3,4),(-3,4),(0,0),(1e-3, 1)]:
    print(f"atan2({y},{x}) = {math.atan2(y,x)} raw16={q16(math.atan2(y,x))}")
for v in [2.0, 0.25, 100.0, 32767.99998, 0.5, 3.0]:
    print(f"sqrt({v})={math.sqrt(v)} raw16={q16(math.sqrt(v))} raw32={q32(math.sqrt(v))}")
