using System.Buffers.Binary;
using Colony.Fields;
using Colony.Hashing;

namespace Colony.ProcGen;

/// <summary>
/// Thrown when a World loaded from a save made with another generation version is asked to (re)generate a chunk
/// (spec section 9.3: regenerating is valid only when the versions match).
/// </summary>
public sealed class GenerationVersionMismatchException : InvalidOperationException
{
    public GenerationVersionMismatchException()
    {
    }

    public GenerationVersionMismatchException(string message)
        : base(message)
    {
    }

    public GenerationVersionMismatchException(string message, Exception innerException)
        : base(message, innerException)
    {
    }

    public GenerationVersionMismatchException(int savedVersion, int currentVersion)
        : base($"The World was saved with generation version {savedVersion}, but the pipeline is version {currentVersion}; regenerating chunks would not reproduce the saved World.")
    {
        SavedVersion = savedVersion;
        CurrentVersion = currentVersion;
    }

    public int SavedVersion { get; }

    public int CurrentVersion { get; }
}

/// <summary>
/// Per-World generation state (spec section 9.3): the <see cref="ChunkProvider"/> seeded with the World seed, the
/// pre-pass values cached in their generated Resources, and the generation version the World's save carries.
/// Host side: <see cref="Apply"/> writes a generated chunk's cells into the Fields and creates its placed Entities.
/// </summary>
public sealed class WorldGeneration : IWorldExtension
{
    private const string VersionSection = "version";

    private readonly GenerationBuilder _definition;
    private readonly ResourceType[] _prePassResources;

    internal WorldGeneration(World world, GenerationBuilder definition, GenerationPipeline pipeline, ResourceType[] prePassResources)
    {
        World = world;
        _definition = definition;
        Pipeline = pipeline;
        _prePassResources = prePassResources;
        Provider = pipeline.CreateProvider(world.Seed);
        StorePrePasses();
    }

    public World World { get; }

    public GenerationPipeline Pipeline { get; }

    /// <summary>The provider for this World's seed (shared, thread-safe).</summary>
    public ChunkProvider Provider { get; }

    /// <summary>The pipeline's generation version.</summary>
    public int Version => Pipeline.Version;

    /// <summary>The generation version recorded in the save this World was loaded from, or null for a fresh World.</summary>
    public int? SavedVersion { get; private set; }

    /// <summary>The pipeline fingerprint recorded in the save this World was loaded from, or null.</summary>
    public ulong? SavedFingerprint { get; private set; }

    /// <summary>False when the World came from a save with another generation version: generating chunks is refused.</summary>
    public bool CanRegenerate => SavedVersion is null || SavedVersion == Version;

    /// <summary>Generates a chunk for this World's seed; throws <see cref="GenerationVersionMismatchException"/> when <see cref="CanRegenerate"/> is false.</summary>
    public GeneratedChunk Generate(ChunkCoord coord)
    {
        ThrowIfMismatched();
        return Provider.Generate(coord);
    }

    /// <summary>Generates a chunk into a reusable buffer.</summary>
    public void Generate(ChunkCoord coord, GeneratedChunk chunk)
    {
        ThrowIfMismatched();
        Provider.Generate(coord, chunk);
    }

    /// <summary>
    /// Writes a generated chunk into the World between Ticks: every Field the pipeline touches gets the chunk's
    /// cells (uniform chunks stay uniform), and each placement becomes an Entity with <see cref="GeneratedEntity"/>
    /// (and <see cref="TilePos"/> when <see cref="GenerationBuilder.TilePos"/> is set), created in placement order.
    /// </summary>
    public void Apply(GeneratedChunk chunk)
    {
        ArgumentNullException.ThrowIfNull(chunk);
        ThrowIfMismatched();
        if (!ReferenceEquals(chunk.Pipeline, Pipeline) || chunk.Seed != World.Seed)
        {
            throw new ArgumentException("The chunk was generated by another pipeline or for another seed.", nameof(chunk));
        }

        var fields = World.Fields();
        if (chunk.Origin != chunk.Coord.Origin || !fields.Size.Contains(chunk.Origin))
        {
            throw new ArgumentException($"Chunk {chunk.Coord} is not a chunk of this World.", nameof(chunk));
        }

        int ordinal = fields.OrdinalOf(chunk.Coord);
        foreach (var field in Pipeline.Fields)
        {
            fields.WriteChunkCells(field.Id, ordinal, chunk.CellBytes(field.Id));
        }

        if (chunk.PlacementCount == 0)
        {
            return;
        }

        var commands = World.CreateCommandBuffer();
        var generated = _definition.GeneratedEntity;
        var tilePos = _definition.TilePos;
        foreach (ref readonly var placement in chunk.Placements)
        {
            var entity = commands.Create();
            commands.Add(entity, generated, new GeneratedEntity(placement.Id, placement.Kind, placement.Data));
            if (tilePos is { } type)
            {
                commands.Add(entity, type, placement.Position);
            }
        }

        World.Playback(commands);
    }

    /// <summary>Generates and applies every chunk of the World in Morton order (a fresh World's initial generation).</summary>
    public void GenerateAll()
    {
        var fields = World.Fields();
        var chunk = Provider.CreateChunk();
        for (int ordinal = 0; ordinal < fields.ChunkCount; ordinal++)
        {
            Generate(fields.ChunkAt(ordinal), chunk);
            Apply(chunk);
        }
    }

    public void BeginTick(long tick)
    {
    }

    public void EndPhase(Phase phase)
    {
    }

    public void EndTick(long tick)
    {
    }

    /// <summary>Nothing: the pre-pass Resources are generated (transient) and the version is schema data.</summary>
    public void Hash(ref Hash64State state)
    {
    }

    public void Save(ExtensionStateWriter writer)
    {
        ArgumentNullException.ThrowIfNull(writer);
        Span<byte> payload = stackalloc byte[12];
        BinaryPrimitives.WriteInt32LittleEndian(payload, Version);
        BinaryPrimitives.WriteUInt64LittleEndian(payload[4..], Pipeline.Fingerprint);
        writer.WriteSection(VersionSection, payload);
    }

    public void Load(ExtensionStateReader reader)
    {
        ArgumentNullException.ThrowIfNull(reader);
        var payload = reader.Section(VersionSection);
        if (payload.Length != 12)
        {
            throw new InvalidDataException($"Section '{VersionSection}' of extension '{reader.ExtensionName}' is {payload.Length} bytes, not 12.");
        }

        SavedVersion = BinaryPrimitives.ReadInt32LittleEndian(payload);
        SavedFingerprint = BinaryPrimitives.ReadUInt64LittleEndian(payload[4..]);
        StorePrePasses();
    }

    public void Dispose()
    {
    }

    private void StorePrePasses()
    {
        var prePasses = Pipeline.PrePasses;
        for (int i = 0; i < prePasses.Length; i++)
        {
            prePasses[i].StoreResource(World, _prePassResources[i], Provider.PrePassBytes(i));
        }
    }

    private void ThrowIfMismatched()
    {
        if (!CanRegenerate)
        {
            throw new GenerationVersionMismatchException(SavedVersion!.Value, Version);
        }
    }
}
