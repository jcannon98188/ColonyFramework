using System.Globalization;
using System.Text;

namespace Colony.Plugins.Native;

/// <summary>
/// Writes <c>colony.h</c> from <see cref="AbiDefinition"/>: status codes and constants, the opaque handle types,
/// every struct with a compile-time size assertion, the callback typedefs, the <c>colony_api</c> function table
/// (one function pointer per entry, in table order) and an index enum per entry so a host can record which
/// entries it exercised. The committed header is <c>src/Colony.Native/colony.h</c>; the Colony.Native tests fail
/// when it differs from this output.
/// </summary>
internal static class HeaderGenerator
{
    public const string FileName = "colony.h";

    public static string Generate()
    {
        var sb = new StringBuilder();
        sb.Append("/* colony.h - the Colony Framework C ABI (spec section 8).\n");
        sb.Append(" * GENERATED by Colony.Plugins.Native.HeaderGenerator from AbiDefinition; do not edit.\n");
        sb.Append(" * Regenerate with: COLONY_ACCEPT_HEADER=1 dotnet test tests/Colony.Native.Tests\n");
        sb.Append(" *\n");
        sb.Append(" * Every function returns a status (COLONY_OK or an error); results travel through out-pointers.\n");
        sb.Append(" * Obtain the table from the Framework library: colony_get_api(COLONY_ABI_VERSION, &api).\n");
        sb.Append(" * A Native Plugin library exports colony_plugin_get(api, &desc) and registers through api->register_*\n");
        sb.Append(" * inside its register callback; its Systems run under the scheduler with the access they declared.\n");
        sb.Append(" * Chunk views are read-only and valid within the callback; command buffers are the only write path.\n");
        sb.Append(" */\n");
        sb.Append("#ifndef COLONY_H\n#define COLONY_H\n\n#include <stddef.h>\n#include <stdint.h>\n\n");
        sb.Append("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");
        sb.Append(CultureInfo.InvariantCulture, $"#define COLONY_ABI_VERSION {ColonyAbi.Version}u\n\n");

        sb.Append("/* Status codes. */\n");
        foreach (var code in AbiDefinition.StatusCodes)
        {
            Define(sb, code);
        }

        sb.Append("\n/* Flags and field kinds. */\n");
        foreach (var constant in AbiDefinition.Constants)
        {
            Define(sb, constant);
        }

        sb.Append("\n/* Opaque handles; only pointers to them cross the boundary. */\n");
        foreach (string handle in AbiDefinition.Handles)
        {
            sb.Append(CultureInfo.InvariantCulture, $"typedef struct {handle} {handle};\n");
        }

        sb.Append("typedef struct colony_api colony_api;\n");

        sb.Append("\n#define COLONY_STATIC_ASSERT(name, condition) typedef char colony_static_assert_##name[(condition) ? 1 : -1]\n");

        // Forward-declare the structs the callbacks mention, then the callbacks, then the structs that hold callbacks.
        sb.Append("\ntypedef struct colony_context colony_context;\ntypedef struct colony_chunk colony_chunk;\ntypedef struct colony_plugin_desc colony_plugin_desc;\n");
        sb.Append("\n/* Callbacks. */\n");
        foreach (var (name, signature, summary) in AbiDefinition.Callbacks)
        {
            sb.Append(CultureInfo.InvariantCulture, $"/* {summary} */\ntypedef {string.Format(CultureInfo.InvariantCulture, signature, name)};\n");
        }

        sb.Append("\n/* Data structures (natural 64-bit alignment; sizes asserted). */\n");
        foreach (var s in AbiDefinition.Structs)
        {
            sb.Append(CultureInfo.InvariantCulture, $"\n/* {s.Summary} */\ntypedef struct {s.Name} {{\n");
            foreach (var (type, name) in s.Fields)
            {
                sb.Append(CultureInfo.InvariantCulture, $"    {type} {name};\n");
            }

            sb.Append(CultureInfo.InvariantCulture, $"}} {s.Name};\nCOLONY_STATIC_ASSERT({s.Name}_size, sizeof({s.Name}) == {s.Size});\n");
        }

        sb.Append("\n/* The function table: version, byte size, then one entry per function in this order. */\n");
        sb.Append("struct colony_api {\n    uint32_t version;\n    uint32_t size;\n");
        foreach (var entry in AbiDefinition.Entries)
        {
            if (entry.Summary.Length > 0)
            {
                sb.Append(CultureInfo.InvariantCulture, $"    /* {entry.Summary} */\n");
            }

            sb.Append(CultureInfo.InvariantCulture, $"    int (*{entry.Name})({string.Join(", ", entry.Parameters)});\n");
        }

        sb.Append("};\n");
        sb.Append(CultureInfo.InvariantCulture, $"COLONY_STATIC_ASSERT(colony_api_size, sizeof(colony_api) == {2 * sizeof(uint) + AbiDefinition.Entries.Length * 8});\n");

        sb.Append("\n/* Index of every entry in the table (COLONY_API_COUNT entries), for conformance bookkeeping. */\n");
        sb.Append("enum colony_api_index {\n");
        for (int i = 0; i < AbiDefinition.Entries.Length; i++)
        {
            sb.Append(CultureInfo.InvariantCulture, $"    COLONY_API_{AbiDefinition.Entries[i].Name.ToUpperInvariant()} = {i},\n");
        }

        sb.Append(CultureInfo.InvariantCulture, $"    COLONY_API_COUNT = {AbiDefinition.Entries.Length}\n}};\n");

        sb.Append("\n/* Exported by the Framework library (Colony.Native). */\nint colony_get_api(uint32_t version, const colony_api** out_api);\n");
        sb.Append("\n#ifdef __cplusplus\n}\n#endif\n\n#endif /* COLONY_H */\n");
        return sb.ToString();
    }

    private static void Define(StringBuilder sb, AbiConstant constant)
    {
        sb.Append(CultureInfo.InvariantCulture, $"#define {constant.Name} {constant.Value}");
        if (!string.IsNullOrEmpty(constant.Summary))
        {
            sb.Append(CultureInfo.InvariantCulture, $" /* {constant.Summary} */");
        }

        sb.Append('\n');
    }
}
